function fetchOembed(url) {
  return new Promise((resolve) => {
    https.get(`https://open.spotify.com/oembed?url=${url}`, (res) => {
      let data = '';
      res.on('data', (chunk) => data += chunk);
      res.on('end', () => {
        try {
          const json = JSON.parse(data);
          resolve(json.title);
        } catch(e) {
          resolve(null);
        }
      });
    }).on('error', () => resolve(null));
  });
}

async function run() {
  const tracks = [];
  const chunkSize = 10;
  for (let i = 0; i < urls.length; i += chunkSize) {
    const chunk = urls.slice(i, i + chunkSize);
    const results = await Promise.all(chunk.map(u => fetchOembed(u)));
    tracks.push(...results.filter(Boolean));
    process.stdout.write(`Fetched ${tracks.length}/${urls.length}\r`);
  }
  fs.writeFileSync('desi_hiphop_tracks.json', JSON.stringify(Array.from(new Set(tracks)), null, 2));
  console.log('\\nDone!');
}

run();
